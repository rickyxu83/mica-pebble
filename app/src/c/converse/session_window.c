static void prv_refresh_timeout(SessionWindow* sw) {
  if (sw->timeout == 0) {
    return;
  }
  if (sw->timeout_handle) {
    app_timer_cancel(sw->timeout_handle);
  }
  BOBBY_LOG(APP_LOG_LEVEL_DEBUG, "Refreshed timeout");
  sw->timeout_handle = app_timer_register(sw->timeout, prv_timed_out, sw);
}

static void prv_cancel_timeout(SessionWindow* sw) {
  if (sw->timeout_handle) {
    app_timer_cancel(sw->timeout_handle);
    sw->timeout_handle = NULL;
  BOBBY_LOG(APP_LOG_LEVEL_DEBUG, "Canceled timeout");
  }
}

static void prv_timed_out(void *ctx) {
  BOBBY_LOG(APP_LOG_LEVEL_DEBUG, "Timed out");
  SessionWindow *sw = ctx;
  mica_animate_window_pop(sw->window);
}

// --- Quiet Time while dictating -------------------------------------------
// The watch cannot change Quiet Time itself; the phone does it through the
// Pebble app's Watch Settings plugin (see pkjs/lib/quiet.js). The watch
// side is a small handshake: QUIET_START asks the phone to engage Quiet
// Time, QUIET_READY (or a timeout - dictation must never be blocked) lets
// dictation start, and QUIET_STOP asks for the previous settings back.

static bool prv_quiet_send(bool start) {
  DictionaryIterator *iter;
  AppMessageResult result = app_message_outbox_begin(&iter);
  if (result != APP_MSG_OK) {
    BOBBY_LOG(APP_LOG_LEVEL_WARNING, "Quiet Time %s request failed to open: %d",
        start ? "start" : "stop", result);
    return false;
  }
  dict_write_uint8(iter, start ? MESSAGE_KEY_QUIET_START : MESSAGE_KEY_QUIET_STOP, 1);
  result = app_message_outbox_send();
  if (result != APP_MSG_OK) {
    BOBBY_LOG(APP_LOG_LEVEL_WARNING, "Quiet Time %s request failed to send: %d",
        start ? "start" : "stop", result);
    return false;
  }
  return true;
}

static void prv_quiet_cancel_stop_retry(SessionWindow *sw) {
  if (sw->quiet_stop_timer) {
    app_timer_cancel(sw->quiet_stop_timer);
    sw->quiet_stop_timer = NULL;
  }
  sw->quiet_stop_attempts = 0;
}

static void prv_quiet_stop_retry(void *context) {
  SessionWindow *sw = context;
  sw->quiet_stop_timer = NULL;
  if (!sw->quiet_engaged || sw->quiet_destroying) {
    return;
  }
  if (prv_quiet_send(false)) {
    sw->quiet_engaged = false;
    sw->quiet_stop_attempts = 0;
    BOBBY_LOG(APP_LOG_LEVEL_INFO, "QUIET_STOP delivered on retry.");
    return;
  }
  if (++sw->quiet_stop_attempts < QUIET_STOP_MAX_ATTEMPTS) {
    sw->quiet_stop_timer = app_timer_register(QUIET_STOP_RETRY_MS, prv_quiet_stop_retry, sw);
  } else {
    // Leave quiet_engaged set: disappear/destroy make a final attempt,
    // and the phone restores on its own after its safety timeout.
    BOBBY_LOG(APP_LOG_LEVEL_WARNING,
        "QUIET_STOP still undelivered after %d attempts; leaving the hold "
        "for the phone-side safety restore.", QUIET_STOP_MAX_ATTEMPTS);
  }
}

static void prv_quiet_release(SessionWindow *sw) {
  if (sw->quiet_timer) {
    app_timer_cancel(sw->quiet_timer);
    sw->quiet_timer = NULL;
  }
  sw->quiet_pending = false;
  if (!sw->quiet_engaged) {
    return;
  }
  // The dictation callback sends the AI request on this same outbox
  // moments before the release runs, and outbox_begin fails BUSY while
  // that message is still in flight - a fire-and-forget QUIET_STOP here
  // was silently dropped (and the hold already marked released), so
  // Quiet Time stayed on until the phone-side safety timeout. Now the
  // hold stays marked engaged until the stop is really on its way, with
  // a retry timer covering the busy window.
  if (prv_quiet_send(false)) {
    sw->quiet_engaged = false;
    prv_quiet_cancel_stop_retry(sw);
    return;
  }
  if (!sw->quiet_destroying && !sw->quiet_stop_timer) {
    sw->quiet_stop_attempts = 0;
    sw->quiet_stop_timer = app_timer_register(QUIET_STOP_RETRY_MS, prv_quiet_stop_retry, sw);
  }
}

static void prv_quiet_ready_timeout(void *context) {
  SessionWindow *sw = context;
  sw->quiet_timer = NULL;
  if (!sw->quiet_pending) {
    return;
  }
  sw->quiet_pending = false;
  BOBBY_LOG(APP_LOG_LEVEL_INFO, "No QUIET_READY in time; starting dictation anyway.");
  prv_start_dictation_now(sw);
}

static void prv_quiet_inbox_received(DictionaryIterator *iter, void *context) {
  Tuple *tuple = dict_find(iter, MESSAGE_KEY_QUIET_READY);
  if (!tuple) {
    return;
  }
  SessionWindow *sw = prv_active_session_window();
  if (!sw || !sw->quiet_pending) {
    return;
  }
  sw->quiet_pending = false;
  if (sw->quiet_timer) {
    app_timer_cancel(sw->quiet_timer);
    sw->quiet_timer = NULL;
  }
  prv_start_dictation_now(sw);
}

static void prv_begin_dictation(SessionWindow *sw) {
  // A dictation the user explicitly asked for starts a fresh turn: forget
  // any interruption state left over from a previous turn.
  sw->dictation_interrupted = false;
  sw->dictation_resume_attempts = 0;
  prv_start_dictation(sw);
}

static void prv_start_dictation(SessionWindow *sw) {
  if (sw->quiet_engaged) {
    // Quiet Time already held for this window (the auto-resume after a
    // system abort, or a QUIET_STOP that is still being retried): the
    // phone still holds it, so the new dictation reuses the hold - just
    // cancel any pending stop retry and start right away.
    prv_quiet_cancel_stop_retry(sw);
    prv_start_dictation_now(sw);
    return;
  }
  if (!settings_get_quiet_listen()) {
    // Setting off: start right away.
    prv_start_dictation_now(sw);
    return;
  }
  sw->quiet_engaged = true;
  sw->quiet_pending = true;
  prv_quiet_send(true);
  sw->quiet_timer = app_timer_register(QUIET_READY_TIMEOUT_MS, prv_quiet_ready_timeout, sw);
}

static void prv_start_dictation_now(SessionWindow *sw) {
  // Dictation needs a ridiculous amount of memory to behave properly.
  free(bmalloc(2048));
#if !ENABLE_FEATURE_FIXED_PROMPT
  if (!sw->dictation) {
    // The phone may have connected after this window was created. Retry rather
    // than caching a NULL session for the lifetime of the window.
    sw->dictation = dictation_session_create(0, prv_dictation_status_callback, sw);
    if (sw->dictation) {
      dictation_session_enable_confirmation(sw->dictation, settings_get_should_confirm_transcripts());
    }
  }
  if (!sw->dictation) {
    conversation_add_error(conversation_manager_get_conversation(sw->manager),
        i18n_is_chinese()
            ? "手机未连接，或当前 Pebble App 不支持语音输入。请检查连接和 App 版本，或返回使用示例问题。"
            : "Phone not connected or dictation is unsupported by this Pebble app. Check the connection/app version or use a sample prompt.");
    return;
  }
  sw->dictation_starting = true;
  DictationSessionStatus start_status = dictation_session_start(sw->dictation);
  sw->dictation_starting = false;
  if (start_status == DictationSessionStatusSuccess) {
    sw->dictation_active = true;
  } else {
    prv_dictation_error(sw, start_status);
  }
#else
  // skip this, just send some nonsense.
  prv_dictation_status_callback(sw->dictation, DictationSessionStatusSuccess, "This is just a test message", sw);
#endif
}
