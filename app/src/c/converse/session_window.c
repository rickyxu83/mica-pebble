#define PADDING 5
// New conversation segments rise into place from this many pixels below
// their resting position, on the settle curve (see util/transition.c):
// a fast rise with a slight overshoot past the resting position.
#define SEGMENT_ARRIVAL_OFFSET_PX 14
#define SEGMENT_ARRIVAL_MS 280
// How long the thinking layer takes to glide after a streaming segment
// whose height changed.
#define THINKING_GLUE_MS 120
// The view counts as "at the bottom" (and so follows new content) when
// it is within this many pixels of the end of the content.
#define SCROLL_FOLLOW_NEAR_BOTTOM_PX 32
// Minimum spacing between animated follow-scrolls; requests made inside
// the window are coalesced into one scroll to the latest target.
#define SCROLL_FOLLOW_MIN_INTERVAL_MS 150
// Raw-touch drag scrolling. A contact becomes a drag once it has moved
// at least this far; shorter contacts are left for the firmware gesture
// bridge's tap handling.
#define TOUCH_DRAG_MIN_DISTANCE_PX 10
#define TOUCH_SAMPLE_COUNT 5
#define TOUCH_VELOCITY_WINDOW_MS 120
// Milli-pixels per millisecond (0.15 px/ms), kept integral to avoid
// floating point in the touch handler.
#define TOUCH_MIN_VELOCITY_MILLI_PX_PER_MS 150
#define TOUCH_INERTIA_PROJECTION_MS 160
#define TOUCH_INERTIA_MIN_MS 150
#define TOUCH_INERTIA_MAX_MS 350
// Synthetic Up/Down presses generated by the gesture bridge for a swipe
// are ignored while the contact is active and for this long afterwards.
#define TOUCH_CLICK_GUARD_MS 150
#define CLARIFICATION_DICTATE_OPTION S(STR_DICTATE)
// How many times a system-interrupted dictation restarts itself before
// giving up and behaving as if the dictation had simply ended.
#define DICTATION_MAX_AUTO_RESUMES 3
// When "Quiet Time while dictating" is on, dictation waits for the phone
// to engage Quiet Time (QUIET_READY) before it starts - but never longer
// than this. A missing or slow reply must never block dictation.
#define QUIET_READY_TIMEOUT_MS 3000
// QUIET_STOP delivery retries: the AppMessage outbox is busy while the AI
// request sent just before it is still in flight, so the stop is retried
// until it goes out (the phone-side safety restore is the last resort).
#define QUIET_STOP_RETRY_MS 250
#define QUIET_STOP_MAX_ATTEMPTS 40

