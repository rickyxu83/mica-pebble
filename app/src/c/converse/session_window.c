// QUIET_READY replies are routed to whichever session window is active;
// one app-lifetime subscription is enough (same pattern as settings.c).
static EventHandle s_quiet_inbox_handle;

void session_window_push(int timeout, char *starting_prompt) {
  if (!s_quiet_inbox_handle) {
    s_quiet_inbox_handle = events_app_message_register_inbox_received(prv_quiet_inbox_received, NULL);
  }
  Window *window = bwindow_create();
  SessionWindow *sw = bmalloc(sizeof(SessionWindow));
  memset(sw, 0, sizeof(SessionWindow));
  window_set_user_data(window, sw);
  sw->window = window;
  sw->timeout = timeout;
  if (starting_prompt != NULL) {
    sw->starting_prompt = bmalloc(strlen(starting_prompt) + 1);
    strncpy(sw->starting_prompt, starting_prompt, strlen(starting_prompt) + 1);
  }
  window_set_window_handlers(window, (WindowHandlers) {
      .load = prv_window_load,
      .unload = prv_window_unload,
      .appear = prv_window_appear,
      .disappear = prv_window_disappear,
  });
  mica_animate_window_push(window);
}

static void prv_destroy(SessionWindow *sw) {
  BOBBY_LOG(APP_LOG_LEVEL_INFO, "destroying SessionWindow %p.", sw);
  // Cancels the QUIET timers (they must never fire on a freed window) and
  // restores Quiet Time if it was still engaged. With quiet_destroying
  // set, the release makes one last send attempt but arms no retry.
  sw->quiet_destroying = true;
  if (sw->quiet_stop_timer) {
    app_timer_cancel(sw->quiet_stop_timer);
    sw->quiet_stop_timer = NULL;
  }
  prv_quiet_release(sw);
  prv_cancel_timeout(sw);
  prv_cancel_arrival_animation(sw);
  prv_cancel_thinking_move(sw);
  prv_cancel_follow_scroll(sw);
  prv_cancel_touch_inertia(sw);
  dictation_session_destroy(sw->dictation);
  for (int i = sw->segments_deleted; i < sw->segment_count; ++i) {
    segment_layer_destroy(sw->segment_layers[i]);
  }
  conversation_manager_destroy(sw->manager);
  status_bar_layer_destroy(sw->status_layer);
  scroll_layer_destroy(sw->scroll_layer);
  bitmap_layer_destroy(sw->button_layer);
  gbitmap_destroy(sw->button_bitmap);
  layer_destroy(sw->scroll_indicator_down);
  if (sw->thinking_layer) {
    thinking_layer_destroy(sw->thinking_layer);
    sw->thinking_layer = NULL;
  }
  free(sw->segment_layers);
  window_destroy(sw->window);
  if (sw->starting_prompt) {
    free(sw->starting_prompt);
  }
  free(sw);
}

static void prv_window_load(Window *window) {
  Layer* root_layer = window_get_root_layer(window);
  GRect window_bounds = layer_get_frame(window_get_root_layer(window));
  GSize window_size = window_bounds.size;
  SessionWindow *sw = window_get_user_data(window);
  sw->dictation_pending = true;
  BOBBY_LOG(APP_LOG_LEVEL_INFO, "created SessionWindow %p.", sw);
  sw->manager = conversation_manager_create();
  conversation_manager_set_handler(sw->manager, prv_conversation_manager_handler, sw);
  conversation_manager_set_deletion_handler(sw->manager, prv_conversation_entry_deleted_handler);
  sw->dictation = dictation_session_create(0, prv_dictation_status_callback, sw);
  dictation_session_enable_confirmation(sw->dictation, settings_get_should_confirm_transcripts());

  sw->segment_space = 3;
  sw->segment_count = 0;
  sw->segments_deleted = 0;
  sw->segment_layers = bmalloc(sizeof(SegmentLayer*) * sw->segment_space);

  sw->status_layer = bstatus_bar_layer_create();
  bobby_status_bar_config(sw->status_layer);
  layer_add_child(root_layer, (Layer *)sw->status_layer);

  sw->content_height = 0;
  sw->last_prompt_end_offset = 0;
  sw->scroll_indicator_down = blayer_create(GRect(0, window_size.h - STATUS_BAR_LAYER_HEIGHT, window_size.w, STATUS_BAR_LAYER_HEIGHT));
  sw->scroll_layer = bscroll_layer_create(GRect(0, STATUS_BAR_LAYER_HEIGHT, window_size.w, window_size.h - STATUS_BAR_LAYER_HEIGHT));
  scroll_layer_set_shadow_hidden(sw->scroll_layer, true);
  // Content size defaults to the (possibly animated) frame; pin it to the
  // full window size so segments created mid-transition keep correct widths.
  scroll_layer_set_content_size(sw->scroll_layer, GSize(window_size.w, window_size.h));
  ContentIndicator* indicator = scroll_layer_get_content_indicator(sw->scroll_layer);
  const ContentIndicatorConfig up_config = (ContentIndicatorConfig) {
    .layer = status_bar_layer_get_layer(sw->status_layer),
    .times_out = true,
    .alignment = GAlignCenter,
    .colors = {
      .foreground = GColorBlack,
      .background = GColorWhite,
    }
  };
  content_indicator_configure_direction(indicator, ContentIndicatorDirectionUp, &up_config);
  const ContentIndicatorConfig down_config = (ContentIndicatorConfig) {
    .layer = sw->scroll_indicator_down,
    .times_out = true,
    .alignment = GAlignCenter,
    .colors = {
      .foreground = GColorBlack,
      .background = GColorWhite,
    },
  };
  content_indicator_configure_direction(indicator, ContentIndicatorDirectionDown, &down_config);
  layer_add_child(root_layer, (Layer *)sw->scroll_layer);
  scroll_layer_set_context(sw->scroll_layer, sw);
  scroll_layer_set_callbacks(sw->scroll_layer, (ScrollLayerCallbacks) {
    .click_config_provider = prv_click_config_provider,
    .content_offset_changed_handler = prv_scrolled_handler,
  });
  scroll_layer_set_click_config_onto_window(sw->scroll_layer, window);

  // This must be added after the scroll layer, to always appear on top.
  sw->button_bitmap = bgbitmap_create_with_resource(RESOURCE_ID_BUTTON_INDICATOR);
  GRect select_indicator_size = gbitmap_get_bounds(sw->button_bitmap);
  grect_align(&select_indicator_size, &window_bounds, GAlignRight, false);
  mica_round_action_indicator(&select_indicator_size);
  sw->button_layer = bbitmap_layer_create(select_indicator_size);
  bitmap_layer_set_bitmap(sw->button_layer, sw->button_bitmap);
  bitmap_layer_set_compositing_mode(sw->button_layer, GCompOpSet);
  layer_add_child(root_layer, (Layer *)sw->button_layer);

  // This must be added last.
  layer_add_child(root_layer, sw->scroll_indicator_down);
  window_set_user_data(sw->window, sw);
}

static void prv_window_appear(Window *window) {
  mica_page_apply_background(window);
  SessionWindow *sw = (SessionWindow *)window_get_user_data(window);
  mica_page_status_bar_colors(sw->status_layer);
  if (sw->starting_prompt) {
    conversation_manager_add_input(sw->manager, sw->starting_prompt);
    sw->query_time = time(NULL);
    free(sw->starting_prompt);
    sw->starting_prompt = NULL;
    sw->dictation_pending = false;
  }
  if (sw->dictation_pending) {
    sw->dictation_pending = false;
    prv_begin_dictation(sw);
  }
  if (sw->dictation_interrupted) {
    // The system tore dictation down (e.g. a notification took over the
    // watch) and the window is visible again: restart dictation so the
    // user can simply continue speaking, unless the conversation has
    // moved on to something else in the meantime.
    sw->dictation_interrupted = false;
    bool can_resume = sw->dictating_clarification ||
        conversation_is_idle(conversation_manager_get_conversation(sw->manager));
    if (can_resume && sw->dictation_resume_attempts < DICTATION_MAX_AUTO_RESUMES) {
      sw->dictation_resume_attempts++;
      BOBBY_LOG(APP_LOG_LEVEL_INFO, "Dictation interrupted by the system; auto-resuming (attempt %d of %d).",
          sw->dictation_resume_attempts, DICTATION_MAX_AUTO_RESUMES);
      prv_start_dictation(sw);
    }
  }
  if (!sw->touch_subscribed) {
    touch_service_subscribe(prv_touch_event_handler, sw);
    sw->touch_subscribed = true;
  }
}

static void prv_window_disappear(Window *window) {
  SessionWindow *sw = (SessionWindow *)window_get_user_data(window);
  // Leaving the window for good ends any Quiet Time hold. While dictation
  // is on screen - or still being presented, which already covers this
  // window before dictation_session_start() returns - the disappear is
  // just the dictation UI covering this window, so the hold stays.
  if (!sw->dictation_active && !sw->dictation_starting) {
    prv_quiet_release(sw);
  }
  if (sw->touch_subscribed) {
    touch_service_unsubscribe();
    sw->touch_subscribed = false;
  }
  sw->touch_dragging = false;
  sw->touch_moved = false;
  sw->touch_sample_count = 0;
  prv_cancel_touch_inertia(sw);
  prv_cancel_timeout(sw);
}

static void prv_window_unload(Window *window) {
  SessionWindow *sw = (SessionWindow *)window_get_user_data(window);
  window_set_user_data(window, (void*)0);
  prv_destroy(sw);
}

static void prv_dictation_error(SessionWindow *sw, DictationSessionStatus status) {
  const char *message;
  if (status == DictationSessionStatusFailureDisabled) {
    message = i18n_is_chinese()
        ? "手机的语音转写已停用。请在 Pebble App 中允许 Usage logs / 语音数据后重试。"
        : "Voice transcription is disabled. Allow Usage logs / voice data in the Pebble phone app and retry.";
  } else if (status == DictationSessionStatusFailureConnectivityError) {
    message = i18n_is_chinese()
        ? "语音需要手机蓝牙和网络连接。请连接手机后重试。"
        : "Dictation needs the phone's Bluetooth and Internet connection.";
  } else if (status == DictationSessionStatusFailureNoSpeechDetected) {
    message = i18n_is_chinese()
        ? "没有听到声音。请靠近手表麦克风，再说一次。"
        : "No speech detected. Speak closer to the watch microphone.";
  } else {
    message = i18n_is_chinese()
        ? "语音识别失败。请检查手机连接和 Pebble App 版本后重试，或返回使用示例问题。"
        : "Dictation failed. Check the phone connection and Pebble app version, or use a sample prompt.";
  }
  BOBBY_LOG(APP_LOG_LEVEL_WARNING, "Dictation failed: %d", (int)status);
  conversation_add_error(conversation_manager_get_conversation(sw->manager), message);
}

static void prv_dictation_status_callback(DictationSession *session, DictationSessionStatus status, char *transcript, void *context) {
  SessionWindow *sw = context;
  sw->dictation_active = false;
  switch (status) {
  case DictationSessionStatusSuccess:
    sw->dictation_interrupted = false;
    sw->dictation_resume_attempts = 0;
    if (sw->dictating_clarification) {
      sw->dictating_clarification = false;
      if (!prv_submit_clarification_answer(sw, transcript, transcript)) {
        conversation_manager_add_input(sw->manager, transcript);
      }
    } else {
      conversation_manager_add_input(sw->manager, transcript);
    }
    sw->query_time = time(NULL);
    break;
  case DictationSessionStatusFailureSystemAborted:
    // The system aborted dictation from outside the app (e.g. an incoming
    // notification dismissed the dictation UI). This is not an error and
    // not a user cancel: remember it so prv_window_appear can restart
    // dictation once this window is visible again. In particular, keep
    // dictating_clarification untouched so a resumed dictation still
    // submits as the clarification answer it started as.
    sw->dictation_interrupted = true;
    BOBBY_LOG(APP_LOG_LEVEL_INFO, "Dictation aborted by the system; will auto-resume when visible.");
    break;
  case DictationSessionStatusFailureTranscriptionRejected:
  case DictationSessionStatusFailureTranscriptionRejectedWithError:
    sw->dictation_interrupted = false;
    sw->dictation_resume_attempts = 0;
    sw->dictating_clarification = false;
    if (conversation_peek(conversation_manager_get_conversation(sw->manager)) == NULL) {
      mica_animate_window_pop(sw->window);
    }
    break;
  default:
    sw->dictation_interrupted = false;
    sw->dictation_resume_attempts = 0;
    sw->dictating_clarification = false;
    prv_dictation_error(sw, status);
    break;
  }
  // Every end of dictation releases the Quiet Time hold - except a system
  // abort, where the hold stays on so the auto-resume (prv_window_appear)
  // dictates under the same protection instead of toggling Quiet Time off
  // and back on around the interruption.
  if (status != DictationSessionStatusFailureSystemAborted) {
    prv_quiet_release(sw);
  }
}

static int16_t prv_holder_width(SessionWindow *sw) {
  // Scroll layer content width follows the transition frame while the
  // native push animation runs; conversation content must always use full width.
  GRect bounds = layer_get_frame(window_get_root_layer(sw->window));
  return bounds.size.w;
}

// --- Small vertical slide animations (segment arrival, thinking glue) ---

typedef struct {
  SessionWindow *sw;
  Layer *layer;
  int16_t from_y;
  int16_t to_y;
  bool snap_on_stop;
  bool is_arrival;
} YSlideContext;

static void prv_slide_update(Animation *animation, const AnimationProgress progress) {
  YSlideContext *ctx = animation_get_context(animation);
  // Arrival slides run on the shared settle curve (their Animation curve
  // is Linear, so this mapping is the only easing); other slides keep
  // the curve the animation system applied to progress.
  const AnimationProgress eased = ctx->is_arrival ?
      mica_curve_settle(progress) : progress;
  GRect frame = layer_get_frame(ctx->layer);
  frame.origin.y = ctx->from_y + (int16_t)(((int32_t)ctx->to_y - (int32_t)ctx->from_y) *
      (int32_t)eased / (int32_t)ANIMATION_NORMALIZED_MAX);
  layer_set_frame(ctx->layer, frame);
}

static void prv_slide_stopped(Animation *animation, bool finished, void *context) {
  YSlideContext *ctx = context;
  SessionWindow *sw = ctx->sw;
  if (finished || ctx->snap_on_stop) {
    GRect frame = layer_get_frame(ctx->layer);
    frame.origin.y = ctx->to_y;
    layer_set_frame(ctx->layer, frame);
  }
  if (ctx->is_arrival) {
    if (sw->arrival_animation == animation) {
      sw->arrival_animation = NULL;
      sw->arrival_layer = NULL;
    }
  } else if (sw->thinking_move_animation == animation) {
    sw->thinking_move_animation = NULL;
  }
  animation_destroy(animation);
  free(ctx);
}

static const AnimationImplementation s_slide_implementation = {
  .update = prv_slide_update,
};

// Slide a layer's frame origin.y to to_y. Any slide already running in
// the same slot is cancelled first (its stopped handler cleans up); the
// new slide starts from the layer's current position, so re-targeting
// mid-flight is continuous.
static void prv_slide_layer_y(SessionWindow *sw, Layer *layer, int16_t to_y,
    uint32_t duration_ms, AnimationCurve curve, bool snap_on_stop, bool is_arrival) {
  Animation **slot = is_arrival ? &sw->arrival_animation : &sw->thinking_move_animation;
  if (*slot) {
    animation_unschedule(*slot);
  }
  GRect frame = layer_get_frame(layer);
  if (frame.origin.y == to_y) {
    return;
  }
  YSlideContext *ctx = bmalloc(sizeof(YSlideContext));
  ctx->sw = sw;
  ctx->layer = layer;
  ctx->from_y = frame.origin.y;
  ctx->to_y = to_y;
  ctx->snap_on_stop = snap_on_stop;
  ctx->is_arrival = is_arrival;
  Animation *animation = animation_create();
  animation_set_duration(animation, duration_ms);
  // Arrival slides ease in prv_slide_update via the settle curve, so
  // their system curve must be Linear to avoid easing twice.
  animation_set_curve(animation, is_arrival ? AnimationCurveLinear : curve);
  animation_set_implementation(animation, &s_slide_implementation);
  animation_set_handlers(animation, (AnimationHandlers) {
    .stopped = prv_slide_stopped,
  }, ctx);
  *slot = animation;
  if (is_arrival) {
    sw->arrival_layer = (SegmentLayer *)layer;
  }
  animation_schedule(animation);
}

static void prv_cancel_arrival_animation(SessionWindow *sw) {
  if (sw->arrival_animation) {
    animation_unschedule(sw->arrival_animation);
  }
}

static void prv_cancel_thinking_move(SessionWindow *sw) {
  if (sw->thinking_move_animation) {
    animation_unschedule(sw->thinking_move_animation);
  }
}

// --- Auto-follow scrolling (animated, coalesced, only from the bottom) ---

static void prv_apply_follow_scroll(SessionWindow *sw) {
  sw->scroll_target_pending = false;
  scroll_layer_set_content_offset(sw->scroll_layer, GPoint(0, sw->pending_scroll_target), true);
  sw->scroll_anim_timer = app_timer_register(SCROLL_FOLLOW_MIN_INTERVAL_MS,
      prv_follow_scroll_timer, sw);
}

static void prv_follow_scroll_timer(void *context) {
  SessionWindow *sw = context;
  sw->scroll_anim_timer = NULL;
  if (sw->scroll_target_pending) {
    prv_apply_follow_scroll(sw);
  }
}

static void prv_request_follow_scroll(SessionWindow *sw, int target) {
  sw->pending_scroll_target = target;
  if (sw->scroll_anim_timer) {
    // Inside the coalescing window: just remember the latest target.
    sw->scroll_target_pending = true;
    return;
  }
  prv_apply_follow_scroll(sw);
}

static void prv_cancel_follow_scroll(SessionWindow *sw) {
  if (sw->scroll_anim_timer) {
    app_timer_cancel(sw->scroll_anim_timer);
    sw->scroll_anim_timer = NULL;
  }
  sw->scroll_target_pending = false;
}

// --- Raw-touch drag scrolling ---

static uint64_t prv_now_ms(void) {
  time_t seconds;
  uint16_t milliseconds;
  time_ms(&seconds, &milliseconds);
  return ((uint64_t)(uint32_t)seconds * 1000) + milliseconds;
}

static int16_t prv_clamp_scroll_offset_y(SessionWindow *sw, int32_t offset_y) {
  if (!sw || !sw->scroll_layer) {
    return 0;
  }
  const GRect scroll_frame = layer_get_frame(scroll_layer_get_layer(sw->scroll_layer));
  const GSize content_size = scroll_layer_get_content_size(sw->scroll_layer);
  int32_t min_offset_y = (int32_t)scroll_frame.size.h - content_size.h;
  if (min_offset_y > 0) {
    min_offset_y = 0;
  }
  if (offset_y < min_offset_y) {
    return (int16_t)min_offset_y;
  }
  if (offset_y > 0) {
    return 0;
  }
  return (int16_t)offset_y;
}

static void prv_touch_record_sample(SessionWindow *sw, int16_t y, uint64_t timestamp_ms) {
  if (sw->touch_sample_count == TOUCH_SAMPLE_COUNT) {
    for (int i = 1; i < TOUCH_SAMPLE_COUNT; ++i) {
      sw->touch_sample_y[i - 1] = sw->touch_sample_y[i];
      sw->touch_sample_time_ms[i - 1] = sw->touch_sample_time_ms[i];
    }
    sw->touch_sample_count = TOUCH_SAMPLE_COUNT - 1;
  }
  sw->touch_sample_y[sw->touch_sample_count] = y;
  sw->touch_sample_time_ms[sw->touch_sample_count] = timestamp_ms;
  sw->touch_sample_count++;
}

static int32_t prv_touch_velocity_milli_px_per_ms(SessionWindow *sw) {
  if (sw->touch_sample_count < 2) {
    return 0;
  }
  const int latest = sw->touch_sample_count - 1;
  int first = latest;
  while (first > 0 &&
      sw->touch_sample_time_ms[latest] - sw->touch_sample_time_ms[first - 1] <=
          TOUCH_VELOCITY_WINDOW_MS) {
    first--;
  }
  const uint64_t elapsed_ms =
      sw->touch_sample_time_ms[latest] - sw->touch_sample_time_ms[first];
  if (first == latest || elapsed_ms == 0) {
    return 0;
  }
  // Samples store finger Y. The content follows the finger directly
  // (offset = start_offset + (finger_y - start_y)), so the offset's
  // velocity is the finger's Y velocity.
  return (int32_t)(sw->touch_sample_y[latest] - sw->touch_sample_y[first]) *
      1000 / (int32_t)elapsed_ms;
}

typedef struct {
  SessionWindow *sw;
  int16_t from_y;
  int16_t to_y;
} TouchInertiaContext;

static void prv_touch_inertia_update(Animation *animation,
    const AnimationProgress progress) {
  TouchInertiaContext *ctx = animation_get_context(animation);
  const int32_t offset_y = ctx->from_y +
      (int32_t)(ctx->to_y - ctx->from_y) * (int32_t)progress /
          (int32_t)ANIMATION_NORMALIZED_MAX;
  scroll_layer_set_content_offset(ctx->sw->scroll_layer,
      GPoint(0, prv_clamp_scroll_offset_y(ctx->sw, offset_y)), false);
}

static void prv_touch_inertia_stopped(Animation *animation, bool finished,
    void *context) {
  TouchInertiaContext *ctx = context;
  SessionWindow *sw = ctx->sw;
  if (finished) {
    scroll_layer_set_content_offset(sw->scroll_layer,
        GPoint(0, prv_clamp_scroll_offset_y(sw, ctx->to_y)), false);
  }
  if (sw->touch_inertia_animation == animation) {
    sw->touch_inertia_animation = NULL;
  }
  animation_destroy(animation);
  free(ctx);
}

static const AnimationImplementation s_touch_inertia_implementation = {
  .update = prv_touch_inertia_update,
};

static void prv_cancel_touch_inertia(SessionWindow *sw) {
  if (sw->touch_inertia_animation) {
    animation_unschedule(sw->touch_inertia_animation);
  }
}

static void prv_start_touch_inertia(SessionWindow *sw, int16_t target_y) {
  const int16_t from_y = scroll_layer_get_content_offset(sw->scroll_layer).y;
  const int32_t distance = target_y >= from_y ?
      (int32_t)target_y - from_y : (int32_t)from_y - target_y;
  if (distance == 0) {
    return;
  }
  prv_cancel_touch_inertia(sw);
  TouchInertiaContext *ctx = bmalloc(sizeof(TouchInertiaContext));
  ctx->sw = sw;
  ctx->from_y = from_y;
  ctx->to_y = target_y;
  Animation *animation = animation_create();
  const uint32_t extra_ms = distance < TOUCH_INERTIA_MAX_MS - TOUCH_INERTIA_MIN_MS ?
      (uint32_t)distance : TOUCH_INERTIA_MAX_MS - TOUCH_INERTIA_MIN_MS;
  animation_set_duration(animation, TOUCH_INERTIA_MIN_MS + extra_ms);
  animation_set_curve(animation, AnimationCurveEaseOut);
  animation_set_implementation(animation, &s_touch_inertia_implementation);
  animation_set_handlers(animation, (AnimationHandlers) {
    .stopped = prv_touch_inertia_stopped,
  }, ctx);
  sw->touch_inertia_animation = animation;
  animation_schedule(animation);
}

static bool prv_touch_click_should_be_ignored(SessionWindow *sw) {
  if (sw->touch_dragging) {
    return true;
  }
  if (sw->touch_last_end_ms == 0) {
    return false;
  }
  const uint64_t now = prv_now_ms();
  return now >= sw->touch_last_end_ms &&
      now - sw->touch_last_end_ms < TOUCH_CLICK_GUARD_MS;
}

static void prv_touch_event_handler(const TouchEvent *event, void *context) {
  SessionWindow *sw = context;
  if (!event || !sw || !sw->touch_subscribed) {
    return;
  }
  if (event->non_navigational || sw->dictation_active ||
      window_stack_get_top_window() != sw->window) {
    // Unarmed watchface contacts and touches delivered while system UI
    // owns the screen are not conversation input.
    sw->touch_dragging = false;
    sw->touch_moved = false;
    sw->touch_sample_count = 0;
    return;
  }

  const uint64_t now = prv_now_ms();
  switch (event->type) {
    case TouchEvent_Touchdown: {
      prv_cancel_follow_scroll(sw);
      prv_cancel_touch_inertia(sw);
      const GPoint offset = scroll_layer_get_content_offset(sw->scroll_layer);
      // Setting the current offset without animation also stops any
      // animated follow-scroll already owned by the ScrollLayer.
      scroll_layer_set_content_offset(sw->scroll_layer, offset, false);
      sw->touch_dragging = true;
      sw->touch_moved = false;
      sw->touch_start_x = event->x;
      sw->touch_start_y = event->y;
      sw->touch_start_offset_y =
          scroll_layer_get_content_offset(sw->scroll_layer).y;
      sw->touch_sample_count = 0;
      prv_touch_record_sample(sw, event->y, now);
      break;
    }
    case TouchEvent_PositionUpdate: {
      if (!sw->touch_dragging) {
        return;
      }
      prv_touch_record_sample(sw, event->y, now);
      const int32_t dx = (int32_t)event->x - sw->touch_start_x;
      const int32_t dy = (int32_t)event->y - sw->touch_start_y;
      if (dx * dx + dy * dy >=
          TOUCH_DRAG_MIN_DISTANCE_PX * TOUCH_DRAG_MIN_DISTANCE_PX) {
        sw->touch_moved = true;
      }
      if (sw->touch_moved) {
        const int16_t offset_y = prv_clamp_scroll_offset_y(sw,
            (int32_t)sw->touch_start_offset_y + event->y - sw->touch_start_y);
        scroll_layer_set_content_offset(sw->scroll_layer,
            GPoint(0, offset_y), false);
      }
      break;
    }
    case TouchEvent_Liftoff: {
      if (!sw->touch_dragging) {
        return;
      }
      prv_touch_record_sample(sw, event->y, now);
      const int32_t dx = (int32_t)event->x - sw->touch_start_x;
      const int32_t dy = (int32_t)event->y - sw->touch_start_y;
      const bool moved = sw->touch_moved || dx * dx + dy * dy >=
          TOUCH_DRAG_MIN_DISTANCE_PX * TOUCH_DRAG_MIN_DISTANCE_PX;
      const int32_t velocity_milli_px_per_ms =
          moved ? prv_touch_velocity_milli_px_per_ms(sw) : 0;
      if (moved) {
        const int16_t offset_y = prv_clamp_scroll_offset_y(sw,
            (int32_t)sw->touch_start_offset_y + event->y - sw->touch_start_y);
        scroll_layer_set_content_offset(sw->scroll_layer,
            GPoint(0, offset_y), false);
      }
      sw->touch_dragging = false;
      sw->touch_moved = false;
      sw->touch_last_end_ms = now;
      sw->touch_sample_count = 0;
      if (velocity_milli_px_per_ms >
              TOUCH_MIN_VELOCITY_MILLI_PX_PER_MS ||
          velocity_milli_px_per_ms <
              -TOUCH_MIN_VELOCITY_MILLI_PX_PER_MS) {
        const int32_t projected_offset_y =
            scroll_layer_get_content_offset(sw->scroll_layer).y +
            velocity_milli_px_per_ms * TOUCH_INERTIA_PROJECTION_MS / 1000;
        prv_start_touch_inertia(sw,
            prv_clamp_scroll_offset_y(sw, projected_offset_y));
      }
      break;
    }
  }
}

static void prv_set_scroll_height(SessionWindow* sw) {
  GSize old_size = scroll_layer_get_content_size(sw->scroll_layer);
  GSize new_size = GSize(prv_holder_width(sw), sw->content_height + PADDING);
  if (old_size.h == new_size.h && old_size.w == new_size.w) {
    return;
  }
  // Decide whether the user is following the tail *before* the size
  // changes: if they have scrolled up to read, new content must not yank
  // the view away from what they are looking at.
  GRect scroll_frame = layer_get_frame(scroll_layer_get_layer(sw->scroll_layer));
  GPoint offset = scroll_layer_get_content_offset(sw->scroll_layer);
  bool at_bottom = old_size.h <= scroll_frame.size.h ||
      (-offset.y + scroll_frame.size.h) >= (old_size.h - SCROLL_FOLLOW_NEAR_BOTTOM_PX);
  scroll_layer_set_content_size(sw->scroll_layer, new_size);
  if (at_bottom && offset.y > -sw->last_prompt_end_offset) {
    prv_request_follow_scroll(sw, -sw->last_prompt_end_offset);
  } else if (new_size.h < old_size.h) {
    // The size shrank: the streaming height estimator overshoots (for
    // CJK text its word-break backtracking finds no breaks), and the
    // exact measurement taken when the response completes is smaller.
    // The old grow-only guard kept the overshoot as a scrollable blank
    // tail forever. Pull an out-of-range offset back into range.
    const int16_t clamped = prv_clamp_scroll_offset_y(sw, offset.y);
    if (clamped != offset.y) {
      scroll_layer_set_content_offset(sw->scroll_layer, GPoint(0, clamped), false);
    }
  }
}

static void prv_update_thinking_layer(SessionWindow* sw) {
  ConversationEntry* entry = conversation_peek(conversation_manager_get_conversation(sw->manager));
  bool visible = false;
  if (entry != NULL) {
    EntryType entry_type = conversation_entry_get_type(entry);
    if (entry_type == EntryTypePrompt || entry_type == EntryTypeAction || entry_type == EntryTypeThought) {
      visible = true;
    } else if (entry_type == EntryTypeResponse) {
      visible = !conversation_entry_get_response(entry)->complete;
    } else if (entry_type == EntryTypeWidget) {
      // Locally created widgets should still have a response coming after.
      visible = conversation_entry_get_widget(entry)->locally_created;
    }
  }

  if (!visible) {
    if (sw->thinking_layer) {
      prv_cancel_thinking_move(sw);
      sw->content_height -= THINKING_LAYER_HEIGHT + 5;
      layer_remove_from_parent(sw->thinking_layer);
      thinking_layer_dismiss(sw->thinking_layer);
      sw->thinking_layer = NULL;
    }
    return;
  }

  GSize holder_size = scroll_layer_get_content_size(sw->scroll_layer);
  if (!sw->thinking_layer) {
    sw->thinking_layer = thinking_layer_create(GRect((prv_holder_width(sw) - THINKING_LAYER_WIDTH) / 2, sw->content_height + 5, THINKING_LAYER_WIDTH, THINKING_LAYER_HEIGHT));
    scroll_layer_add_child(sw->scroll_layer, sw->thinking_layer);
    sw->content_height += THINKING_LAYER_HEIGHT + 5;
    return;
  }

  // Glue: glide to the new resting place instead of teleporting, so the
  // indicator tracks a streaming segment's growth continuously.
  int16_t target_y = sw->content_height - THINKING_LAYER_HEIGHT - 5;
  prv_slide_layer_y(sw, sw->thinking_layer, target_y, THINKING_GLUE_MS,
      AnimationCurveEaseOut, false, false);
}

static int16_t prv_content_height(const SessionWindow* sw) {
  if (sw->thinking_layer) {
    return sw->content_height - THINKING_LAYER_HEIGHT - 5;
  }
  return sw->content_height;
}

static void prv_conversation_manager_handler(bool entry_added, void* context) {
  SessionWindow* sw = context;
  GSize holder_size = scroll_layer_get_content_size(sw->scroll_layer);
  if (!entry_added) {
    if (sw->segment_count > sw->segments_deleted) {
      SegmentLayer *layer = sw->segment_layers[sw->segment_count-1];
      // The update re-lays the segment out; land any arrival slide first.
      if (sw->arrival_layer == layer) {
        prv_cancel_arrival_animation(sw);
      }
      int old_height = layer_get_frame(layer).size.h;
      segment_layer_update(layer);
      int new_height = layer_get_frame(layer).size.h;
      sw->content_height = sw->content_height - old_height + new_height;
      prv_update_thinking_layer(sw);
      prv_set_scroll_height(sw);
      light_enable_interaction();
    }
    return;
  }
  Conversation *conversation = conversation_manager_get_conversation(sw->manager);
  // If we have a new entry, we might just want to replace the old segment layer - we don't
  // keep old Thought segments around.
  if (sw->segment_count > sw->segments_deleted) {
    SegmentLayer* last_layer = sw->segment_layers[sw->segment_count-1];
    EntryType type = conversation_entry_get_type(segment_layer_get_entry(last_layer));
    if (type == EntryTypeThought) {
      // clean it up
      if (sw->arrival_layer == last_layer) {
        prv_cancel_arrival_animation(sw);
      }
      sw->content_height -= layer_get_frame(last_layer).size.h;
      prv_update_thinking_layer(sw);
      prv_set_scroll_height(sw);
      layer_remove_from_parent(last_layer);
      segment_layer_destroy(last_layer);
      sw->segment_layers[--sw->segment_count] = NULL;
      conversation_delete_last_thought(conversation);
    }
  }
  ConversationEntry* entry = conversation_peek(conversation);
  if (entry == NULL) {
    // ??????
    BOBBY_LOG(APP_LOG_LEVEL_ERROR, "We were told a new entry was added, but no entries actually exist????");
    return;
  }
  if (sw->segment_count == sw->segment_space) {
    // make room for a new segment
    SegmentLayer** new_block = bmalloc(sizeof(SegmentLayer*) * ++sw->segment_space);
    memcpy(new_block, sw->segment_layers, sizeof(SegmentLayer*) * sw->segment_count);
    free(sw->segment_layers);
    sw->segment_layers = new_block;
  }
  SegmentLayer* layer = segment_layer_create(GRect(0, prv_content_height(sw), prv_holder_width(sw), 10), entry, conversation_assistant_just_started(conversation));
  sw->segment_layers[sw->segment_count++] = layer;
  // It's possible that the content height changed *while the layer was being created*. In case this happened, move the
  // layer back to where it should be. Because segment layers are expected to adjust their own frame during
  // construction, we must read its size back first.
  GRect frame = layer_get_frame(layer);
  frame.origin.y = prv_content_height(sw);
  layer_set_frame(layer, frame);
  scroll_layer_add_child(sw->scroll_layer, layer);
  // Arrive by sliding up into place instead of popping in fully formed.
  int16_t target_y = layer_get_frame(layer).origin.y;
  GRect start_frame = layer_get_frame(layer);
  start_frame.origin.y = target_y + SEGMENT_ARRIVAL_OFFSET_PX;
  layer_set_frame(layer, start_frame);
  prv_slide_layer_y(sw, layer, target_y, SEGMENT_ARRIVAL_MS,
      AnimationCurveEaseOut, true, true);
  int layer_height = layer_get_frame(layer).size.h;
  sw->content_height += layer_height;
  EntryType entry_type = conversation_entry_get_type(entry);
  if (entry_type == EntryTypePrompt) {
    sw->last_prompt_end_offset = prv_content_height(sw);
  }
  prv_update_thinking_layer(sw);
  prv_set_scroll_height(sw);
  light_enable_interaction();
  prv_refresh_timeout(sw);
  // For responses that took longer than five seconds, pulse the vibe when we get useful data.
  switch (entry_type) {
    case EntryTypeResponse:
    case EntryTypeWidget:
    case EntryTypeAction:
    case EntryTypeError:
      if (sw->query_time > 0) {
        if (time(NULL) >= sw->query_time + 5) {
          vibe_haptic_feedback();
        }
        sw->query_time = 0;
      }
      break;
    case EntryTypePrompt:
    case EntryTypeThought:
    case EntryTypeDeleted:
      // nothing to do here.
      break;
  }
  if (entry_type == EntryTypeResponse || entry_type == EntryTypeWidget || entry_type == EntryTypeAction) {

  }
  // For now, whenever we add a new entry, we want to scroll to the top of it.
//  scroll_layer_set_content_offset(sw->scroll_layer, GPoint(0, layer_get_frame(layer).origin.y), true);
}

static void prv_conversation_entry_deleted_handler(int index, void* context) {
  if (index != 0) {
    BOBBY_LOG(APP_LOG_LEVEL_WARNING, "Invalid index %d", index);
    return;
  }
  SessionWindow* sw = context;
  // Segments are about to be repositioned; land any arrival slide first
  // so the shift applies to final positions.
  prv_cancel_arrival_animation(sw);
  // We need to go through every segment that's left and shift it up by the height of the deleted segment
  SegmentLayer *to_delete = sw->segment_layers[sw->segments_deleted];
  int16_t removed_height = layer_get_frame(to_delete).size.h;
  for (int i = sw->segments_deleted + 1; i < sw->segment_count; ++i) {
    if (sw->segment_layers[i] == NULL) {
      BOBBY_LOG(APP_LOG_LEVEL_WARNING, "Segment layer %d is NULL (not possible!?)", i);
      continue;
    }
    SegmentLayer *layer = sw->segment_layers[i];
    GRect frame = layer_get_frame(layer);
    frame.origin.y -= removed_height;
    layer_set_frame(layer, frame);
  }
  // We need to adjust the height of everything to compensate for the missing segment.
  sw->content_height -= removed_height;
  GPoint current_offset = scroll_layer_get_content_offset(sw->scroll_layer);
  GPoint new_offset = GPoint(current_offset.x, current_offset.y - removed_height);
  scroll_layer_set_content_offset(sw->scroll_layer, new_offset, false);
  GSize current_size = scroll_layer_get_content_size(sw->scroll_layer);
  GSize new_size = GSize(prv_holder_width(sw), current_size.h - removed_height);
  scroll_layer_set_content_size(sw->scroll_layer, new_size);
  // We need to remove our first segment.
  layer_remove_from_parent(to_delete);
  segment_layer_destroy(sw->segment_layers[sw->segments_deleted]);
  sw->segment_layers[sw->segments_deleted] = NULL;
  sw->segments_deleted++;
  BOBBY_LOG(APP_LOG_LEVEL_DEBUG, "Removed top segment; adjusted upward by %d pixels.", removed_height);
}

static void prv_back_clicked(ClickRecognizerRef recognizer, void *context) {
  SessionWindow *sw = context;
  if (sw) {
    // An explicit cancel wins over any pending auto-resume.
    sw->dictation_interrupted = false;
  }
  if (sw && sw->dictation) {
    sw->dictation_active = false;
    dictation_session_stop(sw->dictation);
  }
  if (sw) {
    // dictation_session_stop() delivers no status callback, so the user
    // cancel path releases the Quiet Time hold itself.
    prv_quiet_release(sw);
  }
  // Elastic pop: the mirror image of the elastic push, so the
  // conversation leaves the same way it arrived.
  mica_animate_window_pop(sw->window);
}

